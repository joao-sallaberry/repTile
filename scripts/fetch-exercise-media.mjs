// Downloads the RepDB illustrations of the exercises in src/features/exercises/media-map.json into
// assets/exercise-media/ and writes src/features/exercises/media.generated.ts (the require() map Metro needs).
// Both are git-ignored: RepDB's free-tier license (LICENSE-DATA.md) allows in-app use with attribution, but not
// republishing the images as a dataset, so they must never be committed to this public repo (ADR 0016).
// Runs on `npm install` (postinstall); re-run with `npm run media:fetch`. Never fails the install: without
// network it keeps what is already downloaded.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// Pinned version of https://github.com/sergei-argutin/exercise-dataset (RepDB free tier).
const COMMIT = 'b407c5951a027a27817fb2a5cee9ec9feffc4dc7';
const BASE = `https://raw.githubusercontent.com/sergei-argutin/exercise-dataset/${COMMIT}`;
// Animation order; stretches and holds only have `main`.
const POSES = ['start', 'peak', 'main'];

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'assets/exercise-media');
const generated = join(root, 'src/features/exercises/media.generated.ts');
const map = JSON.parse(readFileSync(join(root, 'src/features/exercises/media-map.json'), 'utf8'));
const ids = [...new Set(Object.values(map).flatMap((byEquipment) => Object.values(byEquipment)))].sort();

mkdirSync(outDir, { recursive: true });
const fileOf = (id, pose) => `${id}-${pose}.webp`;
const local = (id) => POSES.filter((pose) => existsSync(join(outDir, fileOf(id, pose))));

let failed = 0;
const missing = ids.filter((id) => local(id).length === 0);
if (missing.length) {
  try {
    const res = await fetch(`${BASE}/exercises.json`);
    if (!res.ok) throw new Error(`exercises.json: HTTP ${res.status}`);
    const poses = new Map((await res.json()).exercises.map((e) => [e.id, Object.keys(e.images?.flat ?? {})]));
    for (const id of missing) {
      for (const pose of poses.get(id) ?? []) {
        const img = await fetch(`${BASE}/images/flat/${fileOf(id, pose)}`);
        if (!img.ok) {
          failed++;
          continue;
        }
        writeFileSync(join(outDir, fileOf(id, pose)), Buffer.from(await img.arrayBuffer()));
      }
    }
  } catch (e) {
    console.warn(`[exercise-media] download failed (${e.message}); exercises without images will show none.`);
  }
}

const entries = ids
  .map((id) => [id, local(id).sort((a, b) => POSES.indexOf(a) - POSES.indexOf(b))])
  .filter(([, poses]) => poses.length);
writeFileSync(
  generated,
  [
    '// Generated by scripts/fetch-exercise-media.mjs. Do not edit or commit (RepDB license, ADR 0016).',
    'export const FRAMES: Record<string, number[]> = {',
    ...entries.map(
      ([id, poses]) =>
        `  ${JSON.stringify(id)}: [${poses.map((p) => `require('../../../assets/exercise-media/${fileOf(id, p)}')`).join(', ')}],`,
    ),
    '};',
    '',
  ].join('\n'),
);
console.log(`[exercise-media] ${entries.length}/${ids.length} exercises with images${failed ? `, ${failed} files failed` : ''}.`);
