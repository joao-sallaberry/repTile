export async function seedExercises(db: Db) {
  const now = Date.now();
  await db
    .insert(exercises)
    .values(
      SEED.map(([slug, name, category, measure, equipment]) => ({
        id: `seed-${slug}`,
        name,
        category,
        measure,
        equipment: Array.isArray(equipment) ? equipment : [equipment],
        isCustom: false,
        createdAt: now,
        updatedAt: now,
        dirty: false,
      })),
    )
    .onConflictDoNothing();
}
